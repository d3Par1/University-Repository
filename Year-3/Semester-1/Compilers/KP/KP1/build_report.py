def font(run, name='Times New Roman', size=12, bold=False, italic=False):
    run.font.name, run.font.size, run.bold, run.italic = name, Pt(size), bold, italic
    rp = run._element.get_or_add_rPr()
    rf = rp.find(qn('w:rFonts'))
    if rf is None:
        rf = OxmlElement('w:rFonts'); rp.insert(0, rf)
    for a in ('w:ascii', 'w:hAnsi', 'w:cs', 'w:eastAsia'):
        rf.set(qn(a), name)
    return run


def para(text='', bold=False, size=12, align=None, indent=True, italic=False):
    p = doc.add_paragraph()
    pf = p.paragraph_format
    pf.space_after, pf.space_before, pf.line_spacing = Pt(0), Pt(0), 1.15
    pf.first_line_indent = Cm(1.0) if indent else Cm(0)
    p.alignment = align if align is not None else WD_ALIGN_PARAGRAPH.JUSTIFY
    parts = text.split('`')                      # `код` - моноширинним шрифтом
    for i, part in enumerate(parts):
        if part:
            font(p.add_run(part), 'Consolas' if i % 2 else 'Times New Roman', size - (1 if i % 2 else 0), bold, italic)
    return p


def heading(text):
    p = para(text, bold=True, size=13, indent=False, align=WD_ALIGN_PARAGRAPH.LEFT)
    p.paragraph_format.space_before, p.paragraph_format.space_after = Pt(10), Pt(4)
    p.paragraph_format.keep_with_next = True


def code(lines, size=8.5):
    for line in lines:
        p = doc.add_paragraph()
        pf = p.paragraph_format
        pf.space_after, pf.space_before, pf.line_spacing, pf.left_indent = Pt(0), Pt(0), 1.0, Cm(0.3)
        sh = OxmlElement('w:shd')
        sh.set(qn('w:val'), 'clear'); sh.set(qn('w:color'), 'auto'); sh.set(qn('w:fill'), 'F2F2F2')
        p._p.get_or_add_pPr().append(sh)
        font(p.add_run(line.replace('\t', '    ') or ' '), 'Consolas', size)
    doc.add_paragraph().paragraph_format.line_spacing = 0.5


def table(rows, widths, size=9.5):
    t = doc.add_table(rows=len(rows), cols=len(rows[0]))
    t.style = 'Table Grid'
    for r, row in enumerate(rows):
        for c, text in enumerate(row):
            cell = t.cell(r, c)
            cell.width = Cm(widths[c])
            p = cell.paragraphs[0]
            p.paragraph_format.space_after, p.paragraph_format.line_spacing = Pt(0), 1.0
            font(p.add_run(str(text)), 'Times New Roman', size, bold=(r == 0))
    doc.add_paragraph().paragraph_format.line_spacing = 0.5


def field(p, instr):
    r = p.add_run()
    for kind in ('begin', 'instr', 'end'):
        if kind == 'instr':
            el = OxmlElement('w:instrText'); el.text = instr
        else:
            el = OxmlElement('w:fldChar'); el.set(qn('w:fldCharType'), kind)
        r._r.append(el)
    return font(r, size=10)


def run_lexer(text):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        ok = krok_lex.analyze(text)[1]
        print('-' * 30)
        print('tableOfId:{0}'.format(krok_lex.tableOfId))
        print('tableOfConst:{0}'.format(krok_lex.tableOfConst))
    return ok, buf.getvalue().rstrip('\n').split('\n')


def shorten(lines, head=20, tail=5):
    if len(lines) <= head + tail + 1:
        return lines
    return lines[:head] + ['... ({0} рядків пропущено) ...'.format(len(lines) - head - tail)] + lines[-tail:]


