def para(text="", align=J, size=None, bold=False, after=0, indent=True, italic=False):
    p = doc.add_paragraph()
    p.alignment = align
    p.paragraph_format.space_after = Pt(after)
    if indent and align == J:
        p.paragraph_format.first_line_indent = Cm(1.25)
    if text:
        r = p.add_run(text)
        r.bold, r.italic = bold, italic
        if size:
            r.font.size = Pt(size)
    return p


def h1(text):
    return doc.add_heading(text, level=1)


def h2(text):
    return doc.add_heading(text, level=2)


def bullets(items):
    for item in items:
        p = doc.add_paragraph(style="List Bullet")
        p.alignment = J
        p.paragraph_format.space_after = Pt(0)
        if isinstance(item, tuple):
            p.add_run(item[0]).bold = True
            p.add_run(item[1])
        else:
            p.add_run(item)


def shade(cell, fill):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), fill)
    tc_pr.append(shd)


def row_flag(row, tag):
    tr_pr = row._tr.get_or_add_trPr()
    el = OxmlElement(tag)
    el.set(qn("w:val"), "true")
    tr_pr.append(el)


def fill(cell, text, size, bold=False, align=L):
    cell.text = ""
    lines = text if isinstance(text, list) else [text]
    for n, line in enumerate(lines):
        p = cell.paragraphs[0] if n == 0 else cell.add_paragraph()
        p.alignment = align
        p.paragraph_format.line_spacing = 1.0
        p.paragraph_format.space_after = Pt(0)
        r = p.add_run(str(line).replace("UAVS-", "UAVS‑").replace("TC-AG-", "TC‑AG‑"))
        r.font.size = Pt(size)
        r.bold = bold


def table(headers, rows, widths, size=11, center=(), caption=None, label_col=False, space=True, keep=None):
    """Bordered table. `headers=None` gives a key/value table whose first column is shaded."""
    if caption:
        p = para(caption, L, 12, after=3, indent=False, italic=True)
        p.paragraph_format.space_before = Pt(6)
        p.paragraph_format.keep_with_next = True
    elif doc.paragraphs and doc.paragraphs[-1].text and not doc.paragraphs[-1].style.name.startswith("Heading"):
        doc.paragraphs[-1].paragraph_format.space_after = Pt(6)
    t = doc.add_table(rows=0, cols=len(widths))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    if headers:
        row = t.add_row()
        for i, text in enumerate(headers):
            fill(row.cells[i], text, size, bold=True, align=C)
            shade(row.cells[i], "D9D9D9")
        row_flag(row, "w:tblHeader")
    for data in rows:
        row = t.add_row()
        row_flag(row, "w:cantSplit")
        for i, text in enumerate(data):
            fill(row.cells[i], text, size, bold=label_col and i == 0, align=C if i in center else L)
            if label_col and i == 0:
                shade(row.cells[i], "F2F2F2")
    for row in t.rows:
        for i, w in enumerate(widths):
            row.cells[i].width = Cm(w)
    for gc, w in zip(t._tbl.tblGrid.findall(qn("w:gridCol")), widths):   # Word reads tblGrid too
        gc.set(qn("w:w"), str(round(w / 2.54 * 1440)))
    if keep:   # keep a test-case card on one page: "all" rows chain into the next table, "but_last" ends it
        chained = t.rows if keep == "all" else t.rows[:-1]
        for row in chained:
            for cell in row.cells:
                for p in cell.paragraphs:
                    p.paragraph_format.keep_with_next = True
    if space:
        doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return t


