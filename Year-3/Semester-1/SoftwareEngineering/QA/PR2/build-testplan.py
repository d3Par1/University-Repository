def para(text="", align=J, size=None, bold=False, after=0, indent=True, italic=False):
    p = doc.add_paragraph()
    p.alignment = align
    p.paragraph_format.space_after = Pt(after)
    if indent and align == J:
        p.paragraph_format.first_line_indent = Cm(1.25)
    if text:
        r = p.add_run(text)
        r.bold, r.italic = bold, italic
        if size:
            r.font.size = Pt(size)
    return p


def h1(text):
    return doc.add_heading(text, level=1)


def h2(text):
    return doc.add_heading(text, level=2)


def bullets(items):
    for item in items:
        p = doc.add_paragraph(style="List Bullet")
        p.alignment = J
        p.paragraph_format.space_after = Pt(0)
        if isinstance(item, tuple):          # ("bold lead-in", "rest of the sentence")
            p.add_run(item[0]).bold = True
            p.add_run(item[1])
        else:
            p.add_run(item)


def shade(cell, fill):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:val"), "clear")
    shd.set(qn("w:color"), "auto")
    shd.set(qn("w:fill"), fill)
    tc_pr.append(shd)


def row_flag(row, tag):
    tr_pr = row._tr.get_or_add_trPr()
    el = OxmlElement(tag)
    el.set(qn("w:val"), "true")
    tr_pr.append(el)


def table(headers, rows, widths, size=11, center=(), caption=None):
    """Bordered table with a shaded, repeating header row. `widths` are in cm."""
    if caption:
        p = para(caption, L, 12, after=3, indent=False, italic=True)
        p.paragraph_format.space_before = Pt(6)
        p.paragraph_format.keep_with_next = True
    elif doc.paragraphs and doc.paragraphs[-1].text and not doc.paragraphs[-1].style.name.startswith("Heading"):
        doc.paragraphs[-1].paragraph_format.space_after = Pt(6)   # breathing room between text and table
    t = doc.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False

    def fill(cell, text, bold=False, align=L):
        cell.text = ""
        p = cell.paragraphs[0]
        p.alignment = align
        p.paragraph_format.line_spacing = 1.0
        p.paragraph_format.space_after = Pt(0)
        lines = text if isinstance(text, list) else [text]
        for n, line in enumerate(lines):
            if n:
                p = cell.add_paragraph()
                p.alignment = align
                p.paragraph_format.line_spacing = 1.0
                p.paragraph_format.space_after = Pt(0)
            r = p.add_run(str(line).replace("UAVS-", "UAVS‑").replace("TDS-", "TDS‑"))
            r.font.size = Pt(size)
            r.bold = bold

    for i, text in enumerate(headers):
        cell = t.rows[0].cells[i]
        fill(cell, text, bold=True, align=C)
        shade(cell, "D9D9D9")
    row_flag(t.rows[0], "w:tblHeader")
    for data in rows:
        row = t.add_row()
        row_flag(row, "w:cantSplit")
        for i, text in enumerate(data):
            fill(row.cells[i], text, align=C if i in center else L)
    for row in t.rows:
        for i, w in enumerate(widths):
            row.cells[i].width = Cm(w)
    doc.add_paragraph().paragraph_format.space_after = Pt(0)
    return t


