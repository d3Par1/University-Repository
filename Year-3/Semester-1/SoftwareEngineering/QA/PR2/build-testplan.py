def field(paragraph, instr, placeholder=""):
    """Insert a complex Word field (PAGE, TOC ...) into the paragraph."""
    def char(kind):
        r = paragraph.add_run()
        el = OxmlElement("w:fldChar")
        el.set(qn("w:fldCharType"), kind)
        r._r.append(el)
    char("begin")
    r = paragraph.add_run()
    it = OxmlElement("w:instrText")
    it.set(qn("xml:space"), "preserve")
    it.text = instr
    r._r.append(it)
    char("separate")
    paragraph.add_run(placeholder)
    char("end")


